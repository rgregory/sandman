import Foundation

/// Sandman used to be called Artemis. On first launch after the rename this carries the old
/// data folder, settings and launchers across, so managed apps keep working.
enum LegacyMigration {
    static let oldName = "Artemis"
    static let oldBundleID = "com.rgregory.artemis"
    static let oldLauncherIDPrefix = "com.rgregory.artemis.managed."

    static var oldSupport: URL {
        SeatbeltPaths.home.appendingPathComponent("Library/Application Support/\(oldName)")
    }

    /// Runs before anything reads settings or the saved list. Safe to call every launch.
    static func run() {
        moveSupportFolder()
        copySettings()
    }

    /// Application Support/Artemis -> Application Support/Sandman, unless Sandman already has data.
    private static func moveSupportFolder() {
        let fm = FileManager.default
        guard fm.fileExists(atPath: oldSupport.path),
              !fm.fileExists(atPath: SeatbeltPaths.support.path) else { return }
        try? fm.moveItem(at: oldSupport, to: SeatbeltPaths.support)
    }

    /// Theme, sidebar width, Active filter and the rest, from the old bundle ID's defaults.
    private static func copySettings() {
        let flag = "migratedFromArtemis"
        let defaults = UserDefaults.standard
        guard !defaults.bool(forKey: flag),
              let old = UserDefaults.standard.persistentDomain(forName: oldBundleID) else { return }
        for (key, value) in old where defaults.object(forKey: key) == nil {
            defaults.set(value, forKey: key)
        }
        defaults.set(true, forKey: flag)
    }

    /// Launchers made before the rename point at the old profile folder. Rewrites their start
    /// script to the new one. Called once the saved list has loaded.
    static func fixLaunchers(_ entries: [SeatbeltEntry]) {
        let fm = FileManager.default
        var bundles = ((try? fm.contentsOfDirectory(at: SeatbeltPaths.launchers, includingPropertiesForKeys: nil)) ?? [])
            .filter { $0.pathExtension == "app" }
        bundles += entries.filter(\.isReplaced).map { URL(fileURLWithPath: $0.appPath) }
        let oldPath = oldSupport.path + "/"
        let newPath = SeatbeltPaths.support.path + "/"
        for bundle in bundles {
            let script = bundle.appendingPathComponent("Contents/MacOS/launch")
            guard let text = try? String(contentsOf: script, encoding: .utf8), text.contains(oldPath) else { continue }
            let fixed = text.replacingOccurrences(of: oldPath, with: newPath)
                .replacingOccurrences(of: "# Generated by \(oldName).", with: "# Generated by Sandman.")
            try? fixed.write(to: script, atomically: true, encoding: .utf8)
            try? fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: script.path)
        }
    }
}
